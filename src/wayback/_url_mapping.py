"""
Offline tools for mapping old URLs to candidate new URLs after a site has
moved domains and/or reorganized its directory structure.

Researchers typically know a handful of exact old-to-new URL pairs, while the
rest of an index only has old URLs. This module applies explicitly declared
path rules to generate *candidate* new URLs for those old URLs without ever
making a network request.

Design constraints (these are deliberate, not limitations):

* Exact, researcher-provided pairs are the only thing treated as *confirmed*.
* Rule output is always *candidate* and requires human confirmation.
* One-to-many, many-to-one, and contradictory rule results are all retained.
  Candidates are never silently merged because their strings look similar.
* Capture times and content summaries may be attached as *evidence*, but they
  never influence mapping and can never promote a candidate to confirmed.
* Only confirmed mappings are exposed through :meth:`UrlMappingConfig.safe_targets`
  for driving downloads, so unconfirmed candidates cannot overwrite files.
"""

from __future__ import annotations

import csv
from enum import Enum
import json
import re
from typing import Any, Dict, Iterable, List, Mapping, NamedTuple, Optional, Sequence, Tuple
from urllib.parse import urlsplit, urlunsplit

from .exceptions import MappingConfigError


class MappingStatus(str, Enum):
    """
    The certainty of a mapping.

    .. py:attribute:: confirmed

        Based on an exact, researcher-provided old-to-new pair. Safe to use.

    .. py:attribute:: candidate

        Produced by one or more declared rules and/or exceptions. Must be
        reviewed by a human before it can be used.

    .. py:attribute:: unresolved

        No known pair and no rule applied, so no new URL can be suggested.
    """

    confirmed = 'confirmed'
    candidate = 'candidate'
    unresolved = 'unresolved'


class MatchType(str, Enum):
    """
    Where an individual :class:`Candidate` came from.

    .. py:attribute:: exact

        A researcher-provided exact pair.

    .. py:attribute:: rule

        Generated by a declared path rule.

    .. py:attribute:: exception

        Generated by an exception attached to a rule. Exceptions override the
        rule they are attached to for the URLs they match.
    """

    exact = 'exact'
    rule = 'rule'
    exception = 'exception'


class Candidate(NamedTuple):
    """
    A single suggested new URL.

    .. py:attribute:: new_url

        The suggested URL.

    .. py:attribute:: rule_id

        The id of the rule (or exception's rule) that produced this candidate,
        or ``None`` for exact researcher-provided pairs.

    .. py:attribute:: match_type

        How the candidate was produced (see :class:`MatchType`).
    """

    new_url: str
    rule_id: Optional[str]
    match_type: MatchType


class Conflict(NamedTuple):
    """
    A preserved ambiguity that a human reviewer must resolve. Conflicts are
    never resolved automatically, and their candidates are never merged.

    .. py:attribute:: kind

        One of:

        * ``'one_to_many'`` -- one old URL maps to several distinct new URLs
          (either several known pairs or several rules).
        * ``'many_to_one'`` -- several distinct old URLs produce the same new
          URL.
        * ``'rule_conflict'`` -- different rules produce different candidate
          sets for the same old URL.
        * ``'rule_vs_known'`` -- a rule suggests a URL not among the known,
          researcher-provided pairs for an old URL.

    .. py:attribute:: urls

        The new URLs involved in the conflict.

    .. py:attribute:: rule_ids

        The ids of the rules involved, when applicable.

    .. py:attribute:: related_old_urls

        Other old URLs involved (used for ``many_to_one`` conflicts).
    """

    kind: str
    urls: Tuple[str, ...] = ()
    rule_ids: Tuple[Optional[str], ...] = ()
    related_old_urls: Tuple[str, ...] = ()


class MappingResult(NamedTuple):
    """
    The full mapping outcome for a single old URL.

    .. py:attribute:: old_url

        The normalized old URL from the index.

    .. py:attribute:: status

        See :class:`MappingStatus`.

    .. py:attribute:: candidates

        Every candidate, in rule order with duplicates of the *same* URL from
        the *same* source removed. Distinct URLs are always retained.

    .. py:attribute:: conflicts

        All detected ambiguities (see :class:`Conflict`).

    .. py:attribute:: evidence

        Capture times, content summaries, and similar supporting material.
        Evidence is informational only and never affects the mapping.

    .. py:attribute:: notes

        Human-readable notes, such as exceptions that blocked a rule.
    """

    old_url: str
    status: MappingStatus
    candidates: Tuple[Candidate, ...]
    conflicts: Tuple[Conflict, ...]
    evidence: Tuple[Dict[str, Any], ...]
    notes: Tuple[str, ...]

    @property
    def new_urls(self) -> Tuple[str, ...]:
        """Every distinct candidate new URL, in retained order."""
        return tuple(candidate.new_url for candidate in self.candidates)

    @property
    def is_confirmed(self) -> bool:
        """Whether this result is backed by an exact researcher pair."""
        return self.status == MappingStatus.confirmed


_TOKEN_PATTERN = re.compile(r'\{(\w+)\}|\*')
_TEMPLATE_TOKEN_PATTERN = re.compile(r'\{(\w+|\*)\}')
_WILDCARD_TOKEN = '{*}'
_DEFAULT_PORTS = {'http': 80, 'https': 443}


def normalize_url(url: str) -> str:
    """
    Normalize a URL for stable matching and table output.

    The scheme and host are lower-cased, default ports (``:80`` for HTTP and
    ``:443`` for HTTPS) are removed, and an empty path becomes ``/``. The
    path, query, and fragment are otherwise preserved byte-for-byte, because
    their casing and percent-encoding may be significant.

    Raises
    ------
    TypeError
        If ``url`` is not a string.
    ValueError
        If ``url`` does not include a scheme and host.
    """
    if not isinstance(url, str):
        raise TypeError(f'URL must be a string, not {type(url).__name__}')

    parsed = urlsplit(url.strip())
    if not parsed.scheme or not parsed.netloc:
        raise ValueError(f'"{url}" is not an absolute URL with a scheme and host')

    # Lower-case the host part of netloc only; userinfo (before "@") can be
    # case-sensitive.
    if '@' in parsed.netloc:
        userinfo, _, hostport = parsed.netloc.rpartition('@')
        netloc = f'{userinfo}@{hostport.lower()}'
    else:
        netloc = parsed.netloc.lower()

    port = parsed.port
    if port is not None and _DEFAULT_PORTS.get(parsed.scheme.lower()) == port:
        netloc = netloc.rsplit(':', 1)[0]

    path = parsed.path or '/'
    return urlunsplit((parsed.scheme.lower(), netloc, path, parsed.query, parsed.fragment))


def make_evidence(
    captured_at: Optional[str] = None, summary: Optional[str] = None, source: Optional[str] = None, **extra: Any
) -> Dict[str, Any]:
    """
    Build an evidence record (e.g. a capture timestamp and content digest or
    summary). Evidence is carried alongside mappings for reviewer context but
    is never used to derive or confirm a mapping.
    """
    record: Dict[str, Any] = {}
    if captured_at is not None:
        record['captured_at'] = captured_at
    if summary is not None:
        record['summary'] = summary
    if source is not None:
        record['source'] = source
    record.update(extra)
    return record


class _CompiledPattern:
    """A compiled match pattern with ``{param}`` and ``*`` wildcards."""

    def __init__(self, pattern: str):
        self.pattern = pattern
        if '{*}' in pattern:
            raise MappingConfigError(
                f'The "{_WILDCARD_TOKEN}" placeholder is only valid in a "new" template, '
                f'not in the match pattern "{pattern}"; use a bare "*" in patterns'
            )
        parts: List[str] = []
        self.params: List[str] = []
        self.wildcard_slots: List[str] = []
        position = 0
        for token in _TOKEN_PATTERN.finditer(pattern):
            parts.append(re.escape(pattern[position : token.start()]))
            if token.group(1) is not None:
                name = token.group(1)
                if name in self.params:
                    raise MappingConfigError(f'Duplicate parameter "{{{name}}}" in pattern "{pattern}"')
                self.params.append(name)
                parts.append(f'(?P<{name}>[^?#]*)')
            else:
                slot = f'__wildcard_{len(self.wildcard_slots)}'
                self.wildcard_slots.append(slot)
                parts.append(f'(?P<{slot}>.*?)')
            position = token.end()
        parts.append(re.escape(pattern[position:]))
        self.regex = re.compile('^' + ''.join(parts) + '$')

    def match(self, value: str) -> Optional[re.Match]:
        return self.regex.match(value)

    def validate_template(self, template: str) -> None:
        """Eagerly check that a "new" template only uses known params and exactly the pattern's wildcards."""
        wildcard_placeholders = 0
        for token in _TEMPLATE_TOKEN_PATTERN.finditer(template):
            name = token.group(1)
            if name == '*':
                wildcard_placeholders += 1
            elif name not in self.params:
                raise MappingConfigError(
                    f'Template "{template}" references unknown parameter "{{{name}}}"; '
                    f'available parameters are {", ".join(self.params) or "(none)"}'
                )
        if wildcard_placeholders != len(self.wildcard_slots):
            raise MappingConfigError(
                f'Template "{template}" uses {wildcard_placeholders} "{_WILDCARD_TOKEN}" placeholder(s) but '
                f'pattern "{self.pattern}" has {len(self.wildcard_slots)} "*" wildcard(s)'
            )

    def render(self, template: str, match: re.Match) -> str:
        wildcard_index = 0

        def replace(token: re.Match) -> str:
            nonlocal wildcard_index
            name = token.group(1)
            if name != '*':
                if name not in self.params:
                    raise MappingConfigError(
                        f'Template "{template}" references unknown parameter "{{{name}}}"; '
                        f'available parameters are {", ".join(self.params) or "(none)"}'
                    )
                return match.group(name)
            if wildcard_index >= len(self.wildcard_slots):
                raise MappingConfigError(
                    f'Template "{template}" has more "{_WILDCARD_TOKEN}" placeholders than the '
                    f'pattern "{self.pattern}" has "*" wildcards'
                )
            value = match.group(self.wildcard_slots[wildcard_index])
            wildcard_index += 1
            return value

        rendered = _TEMPLATE_TOKEN_PATTERN.sub(replace, template)
        if wildcard_index < len(self.wildcard_slots):
            raise MappingConfigError(
                f'Template "{template}" does not use all "*" wildcards from pattern "{self.pattern}" '
                f'(use "{_WILDCARD_TOKEN}" to insert a wildcard match)'
            )
        return rendered


class _CompiledRule:
    def __init__(self, rule: Mapping[str, Any], index: int):
        if not isinstance(rule, Mapping):
            raise MappingConfigError(f'Rule at index {index} must be an object/dict')
        if 'match' not in rule or 'new' not in rule:
            raise MappingConfigError(f'Rule at index {index} requires both "match" and "new" keys')

        self.id = rule.get('id') or f'rule_{index}'
        self.path_only = rule['match'].startswith('/')
        self.match_pattern = _CompiledPattern(rule['match'])
        self.new_template = rule['new']
        self.match_pattern.validate_template(self.new_template)
        self.exceptions: List[Dict[str, Any]] = []
        for exception_index, exception in enumerate(rule.get('exceptions', [])):
            if not isinstance(exception, Mapping) or 'match' not in exception:
                raise MappingConfigError(
                    f'Exception {exception_index} of rule "{self.id}" must be an object with a "match" key'
                )
            compiled = dict(exception)
            compiled['path_only'] = exception['match'].startswith('/')
            compiled['pattern'] = _CompiledPattern(exception['match'])
            if exception.get('new') is not None:
                compiled['pattern'].validate_template(exception['new'])
            self.exceptions.append(compiled)

    def _match_target(self, url: str, path_only: bool) -> str:
        parsed = urlsplit(url)
        return parsed.path if path_only else url

    def apply(self, old_url: str) -> Tuple[List[Candidate], List[str]]:
        """Return (candidates, notes). An empty candidate list means the rule did not apply."""
        target = self._match_target(old_url, self.path_only)
        match = self.match_pattern.match(target)
        if match is None:
            return [], []

        for exception in self.exceptions:
            exception_target = urlsplit(old_url).path if exception['path_only'] else old_url
            exception_match = exception['pattern'].match(exception_target)
            if exception_match is None:
                continue

            if exception.get('new') is None:
                note = exception.get('note') or 'matched an exception with no replacement'
                return [], [f'Rule "{self.id}" skipped for "{old_url}": {note}']

            rendered = self._render_template(exception['pattern'], exception_match, exception['new'], old_url)
            return [Candidate(rendered, self.id, MatchType.exception)], []

        rendered = self._render_template(self.match_pattern, match, self.new_template, old_url)
        return [Candidate(rendered, self.id, MatchType.rule)], []

    def _render_template(self, pattern: _CompiledPattern, match: re.Match, template: str, old_url: str) -> str:
        rendered = pattern.render(template, match)
        if template.startswith('/'):
            parsed = urlsplit(old_url)
            rendered = urlunsplit((parsed.scheme, parsed.netloc, rendered, parsed.query, parsed.fragment))
        return rendered


class UrlMappingConfig:
    """
    A fully offline configuration for deriving candidate new URLs from old
    ones. Construct it from researcher-provided pairs and explicit rules, then
    call :meth:`apply` or :meth:`build_table`.

    Parameters
    ----------
    known_mappings : mapping, optional
        Exact old-to-new pairs provided by researchers. Values may be a single
        URL string or a list of URLs; a list is retained as a one-to-many
        conflict rather than collapsed.
    rules : list of mapping, optional
        Path rules of the form::

            {
                "id": "domain-move",
                "match": "http://old.example.gov/*",
                "new": "https://new.example.gov/{*}",
                "exceptions": [
                    {"match": "http://old.example.gov/legacy/*",
                     "note": "section retired, no replacement"},
                    {"match": "http://old.example.gov/special",
                     "new": "https://new.example.gov/other"}
                ]
            }

        Patterns support ``{param}`` placeholders (matching any characters
        except ``?`` and ``#``) and ``*`` wildcards. In a template, reference
        parameters as ``{param}`` and wildcards as ``{*}``. A ``match``
        beginning with ``/`` is matched against the URL path only, and a
        template beginning with ``/`` replaces only the path. Exceptions
        without a ``new`` key block the rule; exceptions with ``new`` override
        it.
    """

    def __init__(
        self,
        known_mappings: Optional[Mapping[str, Any]] = None,
        rules: Optional[Sequence[Mapping[str, Any]]] = None,
    ):
        self._known: Dict[str, Tuple[str, ...]] = {}
        for old_url, new_urls in (known_mappings or {}).items():
            normalized_old = normalize_url(old_url)
            if isinstance(new_urls, str):
                new_urls = [new_urls]
            normalized_news = tuple(dict.fromkeys(normalize_url(new_url) for new_url in new_urls))
            if normalized_old in self._known:
                raise MappingConfigError(f'Duplicate known mapping for "{normalized_old}"')
            self._known[normalized_old] = normalized_news

        self._rules = tuple(_CompiledRule(rule, index) for index, rule in enumerate(rules or ()))

    @classmethod
    def from_dict(cls, config: Mapping[str, Any]) -> 'UrlMappingConfig':
        """Build a config from a plain mapping (e.g. parsed JSON)."""
        if not isinstance(config, Mapping):
            raise MappingConfigError('Mapping configuration must be a mapping/object')
        return cls(known_mappings=config.get('known_mappings'), rules=config.get('rules'))

    @property
    def known_mappings(self) -> Mapping[str, Tuple[str, ...]]:
        """The normalized, researcher-provided exact pairs."""
        return dict(self._known)

    def apply(self, old_url: str) -> MappingResult:
        """
        Compute the :class:`MappingResult` for one old URL. Known pairs always
        take precedence, but rule output that disagrees with a known pair is
        still retained as a ``rule_vs_known`` conflict rather than dropped.
        """
        normalized_old = normalize_url(old_url)
        notes: List[str] = []
        conflicts: List[Conflict] = []

        if normalized_old in self._known:
            known_news = self._known[normalized_old]
            candidates = [Candidate(new_url, None, MatchType.exact) for new_url in known_news]
            if len(known_news) > 1:
                conflicts.append(Conflict('one_to_many', urls=known_news))

            extra_candidates, rule_conflicts, rule_notes = self._apply_rules(normalized_old)
            notes.extend(rule_notes)
            disagreeing_candidates = tuple(
                candidate for candidate in extra_candidates if candidate.new_url not in known_news
            )
            if disagreeing_candidates:
                conflicts.append(
                    Conflict(
                        'rule_vs_known',
                        urls=tuple(dict.fromkeys(candidate.new_url for candidate in disagreeing_candidates)),
                        rule_ids=tuple(candidate.rule_id for candidate in disagreeing_candidates),
                    )
                )
                candidates.extend(disagreeing_candidates)
            conflicts.extend(rule_conflicts)
            return MappingResult(
                normalized_old, MappingStatus.confirmed, tuple(candidates), tuple(conflicts), (), tuple(notes)
            )

        candidates, rule_conflicts, rule_notes = self._apply_rules(normalized_old)
        notes.extend(rule_notes)
        conflicts.extend(rule_conflicts)
        status = MappingStatus.candidate if candidates else MappingStatus.unresolved
        return MappingResult(normalized_old, status, tuple(candidates), tuple(conflicts), (), tuple(notes))

    def _apply_rules(self, normalized_old: str) -> Tuple[List[Candidate], List[Conflict], List[str]]:
        candidates: List[Candidate] = []
        seen: set = set()
        notes: List[str] = []
        per_rule_sets: List[Tuple[Optional[str], Tuple[str, ...]]] = []

        for rule in self._rules:
            rule_candidates, rule_notes = rule.apply(normalized_old)
            notes.extend(rule_notes)
            if not rule_candidates:
                continue
            per_rule_sets.append((rule.id, tuple(c.new_url for c in rule_candidates)))
            for candidate in rule_candidates:
                key = (candidate.new_url, candidate.rule_id, candidate.match_type)
                if key not in seen:
                    seen.add(key)
                    candidates.append(candidate)

        conflicts: List[Conflict] = []
        if len(per_rule_sets) > 1:
            distinct_sets = {url_set for _rule_id, url_set in per_rule_sets}
            if len(distinct_sets) > 1:
                conflicts.append(
                    Conflict(
                        'rule_conflict',
                        urls=tuple(dict.fromkeys(url for _rule_id, url_set in per_rule_sets for url in url_set)),
                        rule_ids=tuple(rule_id for rule_id, _url_set in per_rule_sets),
                    )
                )
        all_urls = tuple(candidate.new_url for candidate in candidates)
        if len(set(all_urls)) > 1:
            conflicts.append(
                Conflict(
                    'one_to_many',
                    urls=tuple(dict.fromkeys(all_urls)),
                    rule_ids=tuple(candidate.rule_id for candidate in candidates),
                )
            )
        return candidates, conflicts, notes

    def build_table(
        self, index_urls: Iterable[Any], evidence: Optional[Mapping[str, Any]] = None
    ) -> List[MappingResult]:
        """
        Apply the config to every old URL in an index and return a table of
        :class:`MappingResult` sorted by old URL.

        Parameters
        ----------
        index_urls : iterable
            Old URL strings, or objects (such as :class:`wayback.CdxRecord`)
            exposing an ``original`` attribute.
        evidence : mapping, optional
            Evidence keyed by old URL (raw or normalized). Each value may be a
            single mapping or a list of mappings; use :func:`make_evidence` to
            build them. Evidence is copied onto results for reviewer context
            but never affects any mapping or status.
        """
        normalized_index: List[str] = []
        for item in index_urls:
            url = getattr(item, 'original', item)
            normalized = normalize_url(url)
            if normalized not in normalized_index:
                normalized_index.append(normalized)

        normalized_evidence = self._normalize_evidence(evidence or {})
        results = {old_url: self.apply(old_url) for old_url in normalized_index}

        # Detect many-to-one collisions across the whole table. Exact pairs and
        # rule candidates are both considered, but collisions are reported as
        # conflicts instead of collapsing either side.
        producers: Dict[str, List[str]] = {}
        for old_url in normalized_index:
            for new_url in results[old_url].new_urls:
                producers.setdefault(new_url, []).append(old_url)

        for new_url, old_urls in producers.items():
            if len(set(old_urls)) > 1:
                conflict = Conflict(
                    'many_to_one',
                    urls=(new_url,),
                    related_old_urls=tuple(sorted(set(old_urls))),
                )
                for old_url in set(old_urls):
                    result = results[old_url]
                    results[old_url] = MappingResult(
                        result.old_url,
                        result.status,
                        result.candidates,
                        result.conflicts + (conflict,),
                        result.evidence,
                        result.notes,
                    )

        ordered = []
        for old_url in sorted(results):
            result = results[old_url]
            attached_evidence = normalized_evidence.get(old_url, ())
            if attached_evidence:
                result = MappingResult(
                    result.old_url,
                    result.status,
                    result.candidates,
                    result.conflicts,
                    attached_evidence,
                    result.notes,
                )
            ordered.append(result)
        return ordered

    @staticmethod
    def _normalize_evidence(evidence: Mapping[str, Any]) -> Dict[str, Tuple[Dict[str, Any], ...]]:
        normalized: Dict[str, Tuple[Dict[str, Any], ...]] = {}
        for old_url, records in evidence.items():
            normalized_old = normalize_url(old_url)
            if isinstance(records, Mapping):
                records = [records]
            normalized[normalized_old] = tuple(dict(record) for record in records)
        return normalized

    def safe_targets(self, table: Optional[Sequence[MappingResult]] = None) -> Dict[str, Tuple[str, ...]]:
        """
        Return only mappings safe to use for automated downloads.

        A result qualifies only when it is backed by an exact researcher pair
        (so it is :attr:`MappingResult.is_confirmed`) with a single,
        uncontradicted target. Results with ``one_to_many``, ``rule_conflict``,
        or ``rule_vs_known`` conflicts are excluded because their download
        target is ambiguous, as are all candidate and unresolved results, so
        unconfirmed rules can never overwrite existing files.

        A ``many_to_one`` conflict does not disqualify an otherwise confirmed
        pair: each old URL still has exactly one explicitly provided target.
        The collision remains visible on the review table so the caller can
        decide how to store the downloads.
        """
        results = table if table is not None else self.build_table(self._known)
        return {
            result.old_url: result.new_urls
            for result in results
            if result.is_confirmed
            and not any(
                conflict.kind in ('one_to_many', 'rule_conflict', 'rule_vs_known') for conflict in result.conflicts
            )
        }


def load_mapping_config(path: str) -> UrlMappingConfig:
    """
    Load a :class:`UrlMappingConfig` from a JSON file with the structure::

        {
            "known_mappings": {"http://old.example/a": "https://new.example/b"},
            "rules": [ {"id": "...", "match": "...", "new": "...",
                        "exceptions": [...]} ]
        }
    """
    with open(path, encoding='utf-8') as stream:
        config = json.load(stream)
    return UrlMappingConfig.from_dict(config)


def export_review_csv(table: Sequence[MappingResult], stream: Any) -> None:
    """
    Write a human-reviewable CSV of a mapping table. Every candidate gets its
    own row, unresolved old URLs get a row with an empty candidate column, and
    conflicts and evidence are flattened into columns. The CSV is a review
    artifact, not an input to downloads.
    """
    writer = csv.writer(stream)
    writer.writerow(
        [
            'old_url',
            'status',
            'candidate_new_url',
            'match_type',
            'rule_id',
            'conflict_kinds',
            'evidence_captured_at',
            'evidence_summary',
            'notes',
        ]
    )
    for result in table:
        conflict_kinds = ';'.join(dict.fromkeys(conflict.kind for conflict in result.conflicts))
        captured_at = ' | '.join(str(record.get('captured_at', '')) for record in result.evidence)
        summaries = ' | '.join(str(record.get('summary', '')) for record in result.evidence)
        notes = ' | '.join(result.notes)
        if not result.candidates:
            writer.writerow(
                [result.old_url, result.status.value, '', '', '', conflict_kinds, captured_at, summaries, notes]
            )
        for candidate in result.candidates:
            writer.writerow(
                [
                    result.old_url,
                    result.status.value,
                    candidate.new_url,
                    candidate.match_type.value,
                    candidate.rule_id or '',
                    conflict_kinds,
                    captured_at,
                    summaries,
                    notes,
                ]
            )


